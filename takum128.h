/*
 * takum128 / takum_log128 are an optional extension to libtakum, built
 * separately (see takum128/) because achieving real 128-bit-quality
 * arithmetic (as opposed to just 128-bit storage) requires MPFR/GMP
 * (LGPL) rather than the hardware float types the rest of this ISC,
 * dependency-free library relies on. Nothing here is used by, or
 * changes the behaviour of, takum8/16/32/64.
 *
 * __int128 is a GCC/Clang extension, not standard C99 -- hence
 * __extension__ to keep -Wpedantic quiet for consumers who enable it.
 */
__extension__ typedef __int128 takum128;
__extension__ typedef __int128 takum_log128;

#define TAKUM128_C(hi, lo)                                                     \
	((takum128)((((unsigned __int128)(hi)) << 64) |                        \
	            ((unsigned __int128)(lo))))
#define TAKUM_LOG128_C(hi, lo) ((takum_log128)TAKUM128_C(hi, lo))

/* NaR (Not a Real) */
#define TAKUM128_NAR     ((takum128)(((unsigned __int128)1) << 127))
#define TAKUM_LOG128_NAR ((takum_log128)(((unsigned __int128)1) << 127))

/* Smallest Positive */
#define TAKUM128_POSITIVE_MINIMUM     ((takum128)1)
#define TAKUM_LOG128_POSITIVE_MINIMUM ((takum_log128)1)

/* Largest Positive */
#define TAKUM128_POSITIVE_MAXIMUM     ((takum128)(~TAKUM128_NAR))
#define TAKUM_LOG128_POSITIVE_MAXIMUM ((takum_log128)(~TAKUM_LOG128_NAR))

/*
 * Constant 1: s=0, DR=8 (c=0), all-zero mantissa, i.e. bit 123 set and
 * nothing else -- computed directly since it needs no transcendental
 * evaluation.
 */
#define TAKUM128_ONE     ((takum128)(((unsigned __int128)8) << 123))
#define TAKUM_LOG128_ONE ((takum_log128)(((unsigned __int128)8) << 123))

